"""Compile a ``Timeline`` into a single FFmpeg invocation.

The output is argv only (never a shell string). The filter graph is written to a script
file passed with ``-/filter_complex`` when the local FFmpeg accepts it, else inlined.
All media paths stay separate argv elements; the only names that enter the graph text are
generated by us (the ASS basename, resolved relative to ``RenderPlan.cwd``).
"""
from __future__ import annotations

import functools
import hashlib
import os
import re
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

from ..services.media import StudioError, run
from .timeline import Crop, Overlay, Timeline, VideoClip, VideoTrack

GRADES = {
    'none': [],
    'restrained': ['eq=contrast=1.015:saturation=1.03'],
    'punchy': ['eq=contrast=1.08:saturation=1.18:gamma=0.98', 'unsharp=5:5:0.35:5:5:0'],
    'filmic': ['eq=contrast=1.04:saturation=0.9:brightness=-0.01',
               'colorbalance=rs=0.03:bs=-0.03:rh=-0.02:bh=0.03'],
}
LOUDNESS_TP = -1.5
SAMPLE_RATE = 48000
DUCK = 'threshold=0.02:ratio=10:attack=15:release=350:makeup=1'


@dataclass
class Capabilities:
    version: str
    filters: frozenset
    filter_script: bool

    @property
    def libass(self) -> bool:
        return 'ass' in self.filters


@dataclass
class RenderPlan:
    argv: list
    filter_script: str
    dims: tuple
    duration: float
    has_audio: bool
    cwd: str | None = None
    script_path: str | None = None
    caption_renderer: str | None = None
    fps: float = 30
    warnings: list = field(default_factory=list)


def _binary() -> str:
    full = Path('/opt/homebrew/opt/ffmpeg-full/bin/ffmpeg')
    return os.getenv('FFMPEG_BIN') or (str(full) if full.exists() else 'ffmpeg')


@functools.lru_cache(maxsize=4)
def _capabilities(binary: str) -> Capabilities:
    try:
        version = run(['ffmpeg', '-hide_banner', '-version'])[0].split('\n', 1)[0]
        listing = run(['ffmpeg', '-hide_banner', '-filters'])[0]
    except StudioError:
        return Capabilities('', frozenset(), False)
    names = set()
    for line in listing.splitlines():
        parts = line.split()
        if len(parts) >= 3 and re.fullmatch(r'[TSC.|]{2,3}', parts[0]) and '->' in parts[2]:
            names.add(parts[1])
    script = False
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / 'probe.txt'
        path.write_text('[0:v]null[o]')
        try:
            run(['ffmpeg', '-hide_banner', '-nostdin', '-v', 'error', '-f', 'lavfi', '-i', 'nullsrc=s=16x16:d=0.04',
                 '-/filter_complex', str(path), '-map', '[o]', '-f', 'null', '-'], timeout=30)
            script = True
        except StudioError:
            script = False
    return Capabilities(version, frozenset(names), script)


def ffmpeg_capabilities() -> Capabilities:
    """Runtime feature probe of the FFmpeg binary that ``media.run`` will execute (cached)."""
    return _capabilities(_binary())


def _f(value: float) -> str:
    text = f'{value:.6f}'.rstrip('0').rstrip('.')
    return '0' if text in ('-0', '') else text


def _q(expr: str) -> str:
    return f"'{expr}'"


def piecewise(points, var='t', modes=None) -> str:
    """Expression for a curve through ``points`` [(t, v)], held constant outside the range.

    ``modes[i]`` describes the segment ending at point i: 'linear', 'ease' (cosine) or
    'step' (hold the previous value until t_i, then jump).
    """
    if not points:
        raise ValueError('no points')
    if len(points) == 1:
        return _f(points[0][1])
    modes = modes or ['linear'] * len(points)
    expr = _f(points[-1][1])
    for i in range(len(points) - 1, 0, -1):
        (t0, v0), (t1, v1) = points[i - 1], points[i]
        if modes[i] == 'step' or abs(v1 - v0) < 1e-9:
            segment = _f(v0)
        else:
            p = f'clip(({var}-{_f(t0)})/{_f(t1 - t0)},0,1)'
            shape = f'(0.5-0.5*cos(PI*{p}))' if modes[i] == 'ease' else p
            delta = v1 - v0
            segment = f'{_f(v0)}{"+" if delta >= 0 else "-"}{_f(abs(delta))}*{shape}'
        expr = f'if(lt({var},{_f(t1)}),{segment},{expr})'
    return expr


class _Graph:
    def __init__(self):
        self.stmts: list[str] = []
        self.count = 0

    def label(self, prefix: str) -> str:
        self.count += 1
        return f'{prefix}{self.count}'

    def add(self, ins, filters, outs):
        chain = ','.join(filters) if isinstance(filters, (list, tuple)) else filters
        self.stmts.append(''.join(f'[{i}]' for i in ins) + (chain or 'null') + ''.join(f'[{o}]' for o in outs))


@dataclass
class _Piece:
    clip: VideoClip
    src_in: float
    src_out: float
    offset: float          # clip-local time of this piece's first frame
    zoom: float
    tail: float = 0.0      # extra seconds rendered for an outgoing crossfade
    xfade: float = 0.0     # crossfade duration into this piece
    dip_in: float = 0.0
    dip_out: float = 0.0

    @property
    def nominal(self) -> float:
        return self.src_out - self.src_in


class _Compiler:
    def __init__(self, tl: Timeline, caps: Capabilities, safe_mode: bool):
        self.tl, self.caps, self.safe = tl, caps, safe_mode
        self.g = _Graph()
        self.inputs: list[list[str]] = []
        self.index: dict = {}
        self.warnings: list[str] = []
        self.fps = tl.canvas.fps

    # ---------- inputs ----------
    def _plan_inputs(self, pieces_by_track):
        uses: dict = {}
        for pieces in pieces_by_track.values():
            for p in pieces:
                m = p.clip.media
                if m.kind == 'color':
                    continue
                key = ('still', m.abs_path) if p.clip.still else ('media', m.abs_path)
                lo, hi = uses.get(key, (float('inf'), 0.0))
                if p.clip.still:
                    uses[key] = (0.0, max(hi, p.nominal + p.tail))
                else:
                    uses[key] = (min(lo, p.src_in), max(hi, p.src_out + p.tail))
        for a in self.tl.audio:
            key = ('media', a.media.abs_path)
            lo, hi = uses.get(key, (float('inf'), 0.0))
            uses[key] = (min(lo, a.src_in), max(hi, a.src_out))
        for key, (lo, hi) in uses.items():
            kind, path = key
            if kind == 'still':
                args = ['-loop', '1', '-framerate', _f(self.fps), '-t', _f(hi + 0.5), '-i', path]
                self.index[key] = (len(self.inputs), 0.0)
            else:
                args = ['-ss', f'{lo:.3f}', '-t', _f(hi - lo + 0.25), '-i', path]
                self.index[key] = (len(self.inputs), float(f'{lo:.3f}'))
            self.inputs.append(args)

    # ---------- video ----------
    def _pieces(self, track: VideoTrack):
        frame = self.tl.canvas.frame
        pieces: list[_Piece] = []
        for ci, clip in enumerate(track.clips):
            keys = clip.zoom
            ease = any(k.mode == 'ease' for k in keys) and not self.safe
            bounds = [(0.0, 1.0)]
            if keys and not ease:
                for k in keys:
                    if k.t <= frame / 2:
                        bounds[0] = (0.0, k.zoom)
                    elif clip.length - k.t >= frame:
                        bounds.append((k.t, k.zoom))
            clip_pieces = []
            for i, (t, z) in enumerate(bounds):
                t_end = bounds[i + 1][0] if i + 1 < len(bounds) else clip.length
                clip_pieces.append(_Piece(clip, clip.src_in + t, clip.src_in + t_end, t, z))
            if clip_pieces[-1].nominal < frame and len(clip_pieces) > 1:   # never emit an empty sub-clip
                last = clip_pieces.pop()
                clip_pieces[-1].src_out = last.src_out
            tr = clip.transition_in
            contiguous = bool(pieces) and abs(pieces[-1].clip.end - clip.start) < frame
            if tr.kind == 'crossfade' and tr.duration > 0:
                prev = pieces[-1] if contiguous else None
                room = (prev.clip.media.duration - prev.src_out) if prev and prev.clip.media.kind != 'color' and not prev.clip.still else float('inf')
                if prev and not self.safe and room >= tr.duration:
                    prev.tail = tr.duration
                    clip_pieces[0].xfade = tr.duration
                else:
                    if prev:
                        self.warnings.append(f'clip {clip.id}: crossfade rendered as a dip')
                        prev.dip_out = tr.duration / 2
                    clip_pieces[0].dip_in = tr.duration / 2 if prev else tr.duration
            elif tr.kind == 'dip' and tr.duration > 0:
                if contiguous:
                    pieces[-1].dip_out = tr.duration / 2
                    clip_pieces[0].dip_in = tr.duration / 2
                else:
                    clip_pieces[0].dip_in = tr.duration
            pieces.extend(clip_pieces)
        return pieces

    def _crop_filters(self, crop: Crop, w: int, h: int, zoom: float, offset: float):
        """Filters turning a source frame into a w x h slot frame (excluding fit_blur's split)."""
        a = w / h
        out = []
        if crop.safe_area:
            x, y, cw, ch = crop.safe_area
            out.append(f"crop=w='iw*{_f(cw)}':h='ih*{_f(ch)}':x='iw*{_f(x)}':y='ih*{_f(y)}'")
        if crop.mode == 'fixed':
            x, y, cw, ch = crop.region
            out.append(f"crop=w='iw*{_f(cw)}':h='ih*{_f(ch)}':x='iw*{_f(x)}':y='ih*{_f(y)}'")
        if crop.mode == 'path':
            var = f'(t+{_f(offset)})' if offset else 't'
            pts_x = [(k.t, k.cx) for k in crop.keys]
            pts_y = [(k.t, k.cy) for k in crop.keys]
            zw = f'/{_f(zoom)}' if zoom > 1 else ''
            out.append(f"crop=w='min(iw,ih*{_f(a)}){zw}':h='min(ih,iw/{_f(a)}){zw}'"
                       f":x='clip(({piecewise(pts_x, var)})*iw-ow/2,0,iw-ow)'"
                       f":y='clip(({piecewise(pts_y, var)})*ih-oh/2,0,ih-oh)'")
            out.append(f'scale={w}:{h}')
            return out
        if zoom > 1:
            out.append(f"crop=w='iw/{_f(zoom)}':h='ih/{_f(zoom)}'")
        if crop.mode == 'letterbox':
            out += [f'scale={w}:{h}:force_original_aspect_ratio=decrease',
                    f"pad={w}:{h}:x='(ow-iw)/2':y='(oh-ih)*0.42':color=black"]
        elif crop.mode != 'fit_blur':
            out += [f'scale={w}:{h}:force_original_aspect_ratio=increase', f'crop={w}:{h}']
        return out

    def _piece_chain(self, p: _Piece, w: int, h: int, needs_fps: bool) -> str:
        clip, g = p.clip, self.g
        length = p.nominal + p.tail
        out = g.label('p')
        if clip.media.kind == 'color':
            g.add([], [f'color=c={clip.media.color}:s={w}x{h}:r={_f(self.fps)}:d={_f(length)}', 'setsar=1'], [out])
            src = None
        else:
            idx, pre = self.index[('still', clip.media.abs_path) if clip.still else ('media', clip.media.abs_path)]
            a, b = (0.0, length) if clip.still else (p.src_in - pre, p.src_in - pre + length)
            src = f'{idx}:v'
            head = [f'trim=start={_f(max(0.0, a))}:end={_f(b)}', 'setpts=PTS-STARTPTS']
            if clip.crop.mode == 'fit_blur':
                bg, fg, back, front, joined = (g.label(n) for n in ('bg', 'fg', 'back', 'front', 'j'))
                pre_filters = head + self._crop_filters(clip.crop, w, h, 1.0, p.offset)  # safe_area only
                g.add([src], pre_filters + ['split=2'], [bg, fg])
                g.add([bg], [f'scale={w}:{h}:force_original_aspect_ratio=increase', f'crop={w}:{h}',
                             'boxblur=20:2', 'eq=brightness=-0.15'], [back])
                zoom = [f"crop=w='iw/{_f(p.zoom)}':h='ih/{_f(p.zoom)}'"] if p.zoom > 1 else []
                g.add([fg], zoom + [f'scale={w}:{h}:force_original_aspect_ratio=decrease'], [front])
                g.add([back, front], ['overlay=(W-w)/2:(H-h)/2', 'setsar=1'], [joined])
                src, chain = joined, []
            else:
                chain = head + self._crop_filters(clip.crop, w, h, p.zoom, p.offset) + ['setsar=1']
            chain += GRADES[clip.grade]
            ease_keys = [k for k in clip.zoom]
            if ease_keys and any(k.mode == 'ease' for k in ease_keys) and not self.safe:
                pts, modes = [], []
                if ease_keys[0].t > 0:
                    pts.append((0.0, 1.0)); modes.append('linear')
                for k in ease_keys:
                    pts.append((k.t, k.zoom)); modes.append('ease' if k.mode == 'ease' else 'step')
                z = piecewise(pts, 'it', modes)
                chain.append(f"zoompan=z='{z}':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)'"
                             f':d=1:s={w}x{h}:fps={_f(self.fps)}')
            if p.dip_in:
                chain.append(f'fade=t=in:st=0:d={_f(p.dip_in)}')
            if p.dip_out:
                chain.append(f'fade=t=out:st={_f(max(0.0, length - p.dip_out))}:d={_f(p.dip_out)}')
            if needs_fps:
                chain += [f'fps={_f(self.fps)}', 'format=yuv420p']
            g.add([src], chain, [out])
        return out

    def _run_stream(self, pieces: list[_Piece], w, h) -> str:
        needs_fps = any(p.xfade for p in pieces) or len(pieces) > 1
        labels = [self._piece_chain(p, w, h, needs_fps) for p in pieces]
        acc, pending, acc_len = None, [], 0.0

        def flush():
            group = ([acc] if acc else []) + pending
            if len(group) == 1:
                return group[0]
            lbl = self.g.label('c')
            self.g.add(group, [f'concat=n={len(group)}:v=1:a=0', f'fps={_f(self.fps)}'], [lbl])
            return lbl

        for p, lbl in zip(pieces, labels):
            if p.xfade and (acc or pending):
                acc, pending = flush(), []
                nxt = self.g.label('x')
                # acc already carries p.xfade seconds of tail beyond acc_len
                self.g.add([acc, lbl], f'xfade=transition=fade:duration={_f(p.xfade)}:offset={_f(acc_len)}', [nxt])
                acc = nxt
            else:
                pending.append(lbl)
            acc_len += p.nominal
        return flush()

    def _runs(self, pieces: list[_Piece]):
        frame = self.tl.canvas.frame
        runs, current = [], []
        for p in pieces:
            if current and abs((current[-1].clip.start + current[-1].offset + current[-1].nominal)
                               - (p.clip.start + p.offset)) > frame:
                runs.append(current); current = []
            current.append(p)
        if current:
            runs.append(current)
        return runs

    def video(self) -> str:
        tl, g = self.tl, self.g
        W, H, D = tl.canvas.width, tl.canvas.height, tl.duration
        tracks = sorted(tl.video, key=lambda t: tl.layout.slot(t.slot).z)
        pieces_by_track = {t.slot: self._pieces(t) for t in tracks}
        self._plan_inputs(pieces_by_track)
        layers = []
        for track in tracks:
            slot = tl.layout.slot(track.slot)
            for run_pieces in self._runs(pieces_by_track[track.slot]):
                start = run_pieces[0].clip.start + run_pieces[0].offset
                layers.append((slot, start, run_pieces))
        single = (len(layers) == 1 and layers[0][1] < tl.canvas.frame and layers[0][0].rect.x == 0
                  and layers[0][0].rect.y == 0 and (layers[0][0].rect.w, layers[0][0].rect.h) == (W, H))
        if single:
            acc = self._run_stream(layers[0][2], W, H)
        else:
            acc = g.label('base')
            g.add([], [f'color=c=black:s={W}x{H}:r={_f(self.fps)}:d={_f(D)}', 'setsar=1'], [acc])
            for slot, start, run_pieces in layers:
                stream = self._run_stream(run_pieces, slot.rect.w, slot.rect.h)
                end = start + sum(p.nominal for p in run_pieces)
                if start > 0:
                    shifted = g.label('s')
                    g.add([stream], f'setpts=PTS-STARTPTS+{_f(start)}/TB', [shifted])
                    stream = shifted
                nxt = g.label('v')
                enable = f":enable='between(t,{_f(start)},{_f(end)})'" if start > 0 or end < D - tl.canvas.frame else ''
                g.add([acc, stream], f'overlay=x={slot.rect.x}:y={slot.rect.y}:eof_action=pass{enable}', [nxt])
                acc = nxt
        return acc

    def overlays(self, acc: str, overlays: list[Overlay]) -> str:
        g = self.g
        for ov in sorted(overlays, key=lambda o: o.z):
            if not ov.abs_path:
                raise StudioError('overlay_not_rendered', f'Overlay {ov.id} has no rendered PNG.')
            length = ov.end - ov.start
            idx = len(self.inputs)
            if ov.frames:
                self.inputs.append(['-framerate', _f(self.fps), '-t', _f(length), '-i', ov.abs_path])
            else:
                self.inputs.append(['-loop', '1', '-framerate', _f(self.fps), '-t', _f(length), '-i', ov.abs_path])
            r = ov.rect
            anim = 'fade' if self.safe and ov.animation != 'none' else ov.animation
            chain = ['format=rgba']
            x, y = str(r.x), str(r.y)
            if anim == 'pop':
                s = f'(1-0.18*pow(max(0,1-t/0.22),2))'
                chain.append(f"scale=w='trunc({r.w}*{s}/2)*2':h='trunc({r.h}*{s}/2)*2':eval=frame")
                x, y = f"'{r.x}+({r.w}-w)/2'", f"'{r.y}+({r.h}-h)/2'"
            else:
                chain.append(f'scale={r.w}:{r.h}')
            if anim != 'none':
                fade = min(0.25, length / 3)
                chain += [f'fade=t=in:st=0:d={_f(fade)}:alpha=1',
                          f'fade=t=out:st={_f(length - fade)}:d={_f(fade)}:alpha=1']
            if anim == 'slide_up':
                y = f"'{r.y}+60*pow(max(0,1-(t-{_f(ov.start)})/0.35),2)'"
            chain.append(f'setpts=PTS-STARTPTS+{_f(ov.start)}/TB')
            lbl, nxt = g.label('o'), g.label('v')
            g.add([f'{idx}:v'], chain, [lbl])
            g.add([acc, lbl], f"overlay=x={x}:y={y}:eof_action=pass:enable='between(t,{_f(ov.start)},{_f(ov.end)})'", [nxt])
            acc = nxt
        return acc

    # ---------- audio ----------
    def simple_audio(self):
        """Legacy shape: one source segment aligned with the single source clip -> ``-af``."""
        tl = self.tl
        if len(tl.audio) != 1 or len(tl.video) != 1 or len(tl.video[0].clips) != 1:
            return None
        a, clip = tl.audio[0], tl.video[0].clips[0]
        if (a.role != 'source' or a.media.abs_path != clip.media.abs_path or a.start > 1e-6 or clip.start > 1e-6
                or abs(a.src_in - clip.src_in) > 1e-6 or abs(a.src_out - clip.src_out) > 1e-6 or a.gain_db
                or clip.transition_in.kind == 'crossfade' or clip.still):
            return None
        idx, _ = self.index[('media', a.media.abs_path)]
        return idx, f'loudnorm=I={_f(tl.loudness_lufs)}:TP={LOUDNESS_TP}:LRA=11,alimiter=limit=0.95,aresample={SAMPLE_RATE}'

    def audio(self) -> str | None:
        tl, g = self.tl, self.g
        if not tl.audio:
            return None
        D = tl.duration
        buses: dict[str, list[str]] = {}
        ducks: dict[str, set] = {}
        for a in sorted(tl.audio, key=lambda s: s.start):
            idx, pre = self.index[('media', a.media.abs_path)]
            chain = [f'atrim=start={_f(max(0.0, a.src_in - pre))}:end={_f(a.src_out - pre)}', 'asetpts=PTS-STARTPTS',
                     f'aresample={SAMPLE_RATE}', 'aformat=sample_fmts=fltp:channel_layouts=stereo']
            if a.fade_in:
                chain.append(f'afade=t=in:st=0:d={_f(a.fade_in)}')
            if a.fade_out:
                chain.append(f'afade=t=out:st={_f(a.length - a.fade_out)}:d={_f(a.fade_out)}')
            if a.gain_db:
                chain.append(f'volume={_f(a.gain_db)}dB')
            delay = round(a.start * SAMPLE_RATE)
            if delay:
                chain.append(f'adelay=delays={delay}S:all=1')
            lbl = g.label('a')
            g.add([f'{idx}:a'], chain, [lbl])
            buses.setdefault(a.role, []).append(lbl)
            ducks.setdefault(a.role, set()).update(a.duck_under)
        bus_label = {}
        for role, labels in buses.items():
            out = g.label(f'{role}_')
            mix = [f'amix=inputs={len(labels)}:normalize=0:duration=longest'] if len(labels) > 1 else []
            g.add(labels, mix + [f'apad=whole_dur={_f(D)}'], [out])
            bus_label[role] = out
        # sidechain keys: each bus is consumed once by the final mix plus once per role it ducks.
        consumers = {role: 1 for role in bus_label}
        for role, under in ducks.items():
            for key in under:
                if key in bus_label:
                    consumers[key] += 1
        copies: dict[str, list[str]] = {}
        for role, n in consumers.items():
            if n == 1:
                copies[role] = [bus_label[role]]
            else:
                outs = [g.label(f'{role}_c') for _ in range(n)]
                g.add([bus_label[role]], f'asplit={n}', outs)
                copies[role] = outs
        final = {}
        for role in bus_label:
            final[role] = copies[role].pop(0)
        for role, under in ducks.items():
            keys = [copies[k].pop(0) for k in sorted(under) if k in bus_label]
            if not keys:
                continue
            if len(keys) > 1:
                key = g.label('key')
                g.add(keys, f'amix=inputs={len(keys)}:normalize=0:duration=longest', [key])
            else:
                key = keys[0]
            ducked = g.label(f'{role}_d')
            g.add([final[role], key], f'sidechaincompress={DUCK}', [ducked])
            final[role] = ducked
        out = 'aout'
        tail = [f'loudnorm=I={_f(tl.loudness_lufs)}:TP={LOUDNESS_TP}:LRA=11', 'alimiter=limit=0.95',
                f'aresample={SAMPLE_RATE}', f'atrim=end={_f(D)}']
        labels = list(final.values())
        mix = [f'amix=inputs={len(labels)}:normalize=0:duration=longest'] if len(labels) > 1 else []
        g.add(labels, mix + tail, [out])
        return out


def _caption_mode(tl: Timeline, caps: Capabilities, strict: bool, warnings: list) -> str | None:
    track = tl.captions
    if not track:
        return None
    renderer = track.renderer
    if renderer == 'auto':
        renderer = 'ass' if caps.libass and (track.ass_file or track.cues) else 'png'
    if renderer == 'ass' and not caps.libass and strict:
        raise StudioError('libass_required', 'ASS captions need an FFmpeg build with libass; use PNG captions instead.')
    if renderer == 'png' and track.cues and not any(o.kind == 'caption' for o in tl.overlays):
        warnings.append('Caption cues supplied but no rendered caption overlays; captions were not burned in.')
    return renderer


def _ass_text(cue, mode):
    original = cue.text
    text = {'original': original, 'english': cue.translated_english or original,
            'hindi': cue.translated_hindi or original,
            'bilingual': original + ('\n' + (cue.translated_hindi or cue.translated_english) if (cue.translated_hindi or cue.translated_english) else '')}[mode]
    return text.replace('\\', '').replace('{', '').replace('}', '').replace('\r', '').replace('\n', r'\N')


def _ass_time(t):
    cs = round(t * 100)
    return f'{cs // 360000}:{cs // 6000 % 60:02d}:{cs // 100 % 60:02d}.{cs % 100:02d}'


def write_ass(tl: Timeline, workdir: Path) -> Path:
    """Minimal ASS for a CaptionTrack without a prebuilt file (libass builds only)."""
    track, W, H = tl.captions, tl.canvas.width, tl.canvas.height
    r = track.safe_rect
    size = max(24, W // 18)
    lines = ['[Script Info]', 'ScriptType: v4.00+', f'PlayResX: {W}', f'PlayResY: {H}', 'WrapStyle: 0', '',
             '[V4+ Styles]',
             'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, '
             'Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
             f'Style: Main,Arial Unicode MS,{size},&H00FFFFFF,&H00FFFFFF,&H00000000,&H64000000,1,0,0,0,100,100,0,0,1,'
             f'{max(2, size // 12)},1,2,{r.x},{W - r.x - r.w},{H - r.y - r.h},1', '',
             '[Events]', 'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text']
    for cue in track.cues:
        lines.append(f'Dialogue: 0,{_ass_time(cue.start)},{_ass_time(cue.end)},Main,,0,0,0,,{_ass_text(cue, track.mode)}')
    digest = hashlib.sha1('\n'.join(lines).encode()).hexdigest()[:10]
    path = Path(workdir) / f'captions_{digest}.ass'
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return path


def compile(timeline: Timeline, workdir=None, *, output=None, inline: bool | None = None,
            x264_preset: str = 'veryfast', crf: int = 21, safe_mode: bool = False,
            capabilities: Capabilities | None = None, strict_capabilities: bool = True) -> RenderPlan:
    """Build the FFmpeg argv for ``timeline``.

    ``workdir`` receives the filter script (and a generated ASS file); with ``workdir=None``
    or ``inline=True`` the graph is passed inline. ``safe_mode`` is the repair profile:
    no zoompan, no xfade, fade-only overlays, single encoder thread.
    """
    tl = timeline
    caps = capabilities or ffmpeg_capabilities()
    c = _Compiler(tl, caps, safe_mode)
    W, H, D = tl.canvas.width, tl.canvas.height, tl.duration
    acc = c.video()
    simple = c.simple_audio()
    cards = [o for o in tl.overlays]
    acc = c.overlays(acc, cards)
    renderer = _caption_mode(tl, caps, strict_capabilities, c.warnings)
    tail = []
    if tl.fade_in:
        tail.append(f'fade=t=in:d={_f(tl.fade_in)}')
    if tl.fade_out:
        tail.append(f'fade=t=out:st={max(0, D - tl.fade_out):.3f}:d={_f(tl.fade_out)}')
    cwd = None
    if renderer == 'ass':
        ass = tl.captions.abs_path
        if not ass:
            if workdir is None:
                raise StudioError('workdir_required', 'Generated ASS captions need a work directory.')
            ass = str(write_ass(tl, Path(workdir)))
        # Basename only, with cwd = its folder: avoids filter path escaping entirely.
        tail.append(f'ass={Path(ass).name}')
        cwd = str(Path(ass).parent)
    c.g.add([acc], tail or ['null'], ['out'])
    audio_label = None if simple else c.audio()
    has_audio = bool(tl.audio) and any(a.media.has_audio for a in tl.audio)
    graph_inline = ';'.join(c.g.stmts)
    script = ';\n'.join(c.g.stmts) + '\n'
    use_script = (not inline) and workdir is not None and caps.filter_script
    if inline is False and not caps.filter_script:
        c.warnings.append('FFmpeg does not accept -/filter_complex; graph passed inline.')
    argv = ['ffmpeg', '-hide_banner', '-nostdin', '-y', '-threads', '1' if safe_mode else '2',
            '-filter_complex_threads', '1']
    for args in c.inputs:
        argv += args
    script_path = None
    if use_script:
        script_path = Path(workdir) / f'graph_{hashlib.sha1(script.encode()).hexdigest()[:12]}.txt'
        script_path.write_text(script, encoding='utf-8')
        argv += ['-/filter_complex', str(script_path.resolve())]
    else:
        argv += ['-filter_complex', graph_inline]
    argv += ['-map', '[out]']
    if simple:
        argv += ['-map', f'{simple[0]}:a:0?']
    elif audio_label:
        argv += ['-map', f'[{audio_label}]']
    argv += ['-t', f'{D:.3f}', '-r', f'{tl.canvas.fps:.6f}', '-c:v', 'libx264', '-preset', x264_preset,
             '-crf', str(crf), '-pix_fmt', 'yuv420p', '-threads', '1' if safe_mode else '2']
    if has_audio:
        if simple:
            argv += ['-af', simple[1]]
        argv += ['-c:a', 'aac', '-b:a', '160k']
    out = output if output is not None else (Path(workdir) / 'render.mp4' if workdir else 'render.mp4')
    argv += ['-movflags', '+faststart', '-max_muxing_queue_size', '1024', str(out)]
    return RenderPlan(argv=argv, filter_script=script, dims=(W, H), duration=D, has_audio=has_audio, cwd=cwd,
                      script_path=str(script_path) if script_path else None, caption_renderer=renderer,
                      fps=tl.canvas.fps, warnings=c.warnings)
