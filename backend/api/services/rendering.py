import re
from .media import run, probe, StudioError


def render_command(source, output, start, duration, info, resolution, layout, caption=None):
    width, height = (1080, 1920) if resolution == '1080' else (720, 1280)
    # Do not imply a low-resolution input supports a native 1080 output.
    if info['height'] < 1080 and resolution == '1080':
        width, height = 720, 1280
    fps = 60 if info['fps'] >= 50 and resolution == '1080' else min(30, info['fps'])
    if layout == 'center':
        graph = f'[0:v]scale={width}:{height}:force_original_aspect_ratio=increase,crop={width}:{height},setsar=1[v]'
    else:
        graph = (f'[0:v]split=2[bg][fg];[bg]scale={width}:{height}:force_original_aspect_ratio=increase,'
                 f'crop={width}:{height},boxblur=20:2,eq=brightness=-0.15[back];'
                 f'[fg]scale={width}:{height}:force_original_aspect_ratio=decrease[front];'
                 f'[back][front]overlay=(W-w)/2:(H-h)/2,setsar=1[v]')
    graph += f';[v]eq=contrast=1.015:saturation=1.03,fade=t=in:d=0.12,fade=t=out:st={max(0,duration-.18):.3f}:d=0.18'
    if caption:
        # Caption basename is generated by us, cwd is its parent; avoids filter path escaping.
        graph += f',ass={caption.name}'
    graph += '[out]'
    command = ['ffmpeg', '-hide_banner', '-nostdin', '-y', '-threads', '2', '-filter_complex_threads', '1',
        '-ss', f'{start:.3f}', '-i', str(source), '-t', f'{duration:.3f}', '-filter_complex', graph,
        '-map', '[out]', '-map', '0:a:0?', '-r', f'{fps:.6f}', '-c:v', 'libx264',
        '-preset', 'veryfast', '-crf', '21', '-pix_fmt', 'yuv420p', '-threads', '2']
    if info['has_audio']:
        command += ['-af', 'loudnorm=I=-16:TP=-1.5:LRA=11,alimiter=limit=0.95', '-c:a', 'aac', '-b:a', '160k']
    command += ['-movflags', '+faststart', '-max_muxing_queue_size', '1024', str(output)]
    return command, (width, height)


def validate_output(path, expected_duration, dimensions, audio):
    info = probe(path)
    checks = {'video_stream': True, 'dimensions': (info['width'],info['height']) == dimensions,
              'duration': abs(info['duration']-expected_duration) < .6,
              'audio_stream': not audio or info['has_audio']}
    _, diagnostics = run(['ffmpeg', '-hide_banner', '-nostdin', '-i', path,
        '-vf', 'blackdetect=d=0.5:pix_th=0.10,freezedetect=n=-50dB:d=2',
        *(['-af', 'volumedetect'] if audio else []), '-f', 'null', '-'])
    # Static scenes and dark footage can be intentional; flag for review rather than invent a repair.
    black = bool(re.search(r'black_start:', diagnostics))
    frozen = 'freeze_start:' in diagnostics
    peak = re.search(r'max_volume: (-?[\d.]+) dB', diagnostics)
    clipping = bool(peak and float(peak[1]) >= -.1)
    _, errors = run(['ffmpeg', '-v', 'error', '-nostdin', '-i', path, '-f', 'null', '-'])
    checks['full_decode'] = not errors.strip()
    flags = []
    if black:
        flags.append('Dark frames detected; review whether intentional.')
    if frozen:
        flags.append('Static or frozen section detected; review source.')
    if clipping:
        flags.append('Audio peaks need review.')
    unverified = ['Semantic coherence and final-word completeness', 'Caption accuracy and visual readability',
                  'Perceptual A/V synchronization', 'Ownership and monetization eligibility']
    score = max(0, 100 - 20*sum(not ok for ok in checks.values()) - 8*len(flags))
    return dict(score=score, checks=checks, flags=flags, unverified=unverified,
                basis='Technical checks and editorial heuristics; not a retention prediction.')
